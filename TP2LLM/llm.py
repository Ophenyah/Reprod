import math
import random
import sys
import argparse

TRIALS = 1_000_000
SEED = 20261019

def associativity():
    rng = random.Random(SEED)
    equal = 0

    for _ in range(TRIALS):
        x = rng.uniform(-1e16, 1e16)
        y = rng.uniform(-1e16, 1e16)
        z = rng.uniform(-1e16, 1e16)

        if (x + y) + z == x + (y + z):
            equal += 1

    percentage = 100.0 * equal / TRIALS
    print(f"{percentage:.6f}") #Ophélia : Removed the % to be consistant



def associativity_arg(nb, pp):
    rng = random.Random(SEED)
    equal = 0

    for _ in range(nb):
        x = rng.uniform(-1e16, 1e16)
        y = rng.uniform(-1e16, 1e16)
        z = rng.uniform(-1e16, 1e16)

        if (x + y) + z == x + (y + z):
            equal += 1

    percentage = 100.0 * equal / nb
    if pp:
        print( f"({nb};{percentage:.6f})")
    else:
        print(f"{percentage:.6f}") #Ophélia : Removed the % to be consistant

def bank():
    balance = math.e

    for year in range(1, 51):
        balance = (balance - 1.0) * year

    balance -= 1.0
    print(balance)


