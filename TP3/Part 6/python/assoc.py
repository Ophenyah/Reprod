def associativity_arg(it, rn, type):
    rng = random.Random(SEED)
    equal = 0


    min = 0
    max = 0

    if it==0:
        it=100
    elif it==1:
        it=1000
    elif it==2:
        it= 1000000


    if rn==0:
        min = 0.0
        max = 1.0
    elif rn==1:
        min=-1e16
        max=1e16
    elif rn==2:
        min=-1e10
        max=1e10

    if type==0:
        for _ in range(it):
            x = rng.uniform(min, max)
            y = rng.uniform(min, max)
            z = rng.uniform(min, max)

            if (x + y) + z == x + (y + z):
                equal += 1
    elif type==1:
        for _ in range(it):
            min = Decimal(str(min))
            max = Decimal(str(max))
            x = min + (max - min) * Decimal(str(rng.random()))
            y = min + (max - min) * Decimal(str(rng.random()))
            z = min + (max - min) * Decimal(str(rng.random()))

            if (x + y) + z == x + (y + z):
                equal += 1

    percentage = 100.0 * equal / it
    print(f"{percentage:.6f}") #Ophélia : Removed the % to be consistant

